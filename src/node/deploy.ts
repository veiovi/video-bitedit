// One-command Cloudflare setup: create the D1 database and R2 bucket if they
// are missing, write wrangler.jsonc, apply migrations, set the workspace key,
// build and deploy the Worker, then save the server URL locally.
//
// Needs CLOUDFLARE_API_TOKEN (Workers, D1 and R2 edit permissions). Set
// CLOUDFLARE_ACCOUNT_ID too if the token can see more than one account.

import { execFile, spawn } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { newId } from '../shared/project';
import { loadConfig, readConfigFile, saveConfig } from './config';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const run = promisify(execFile);

export interface DeployOptions {
  name?: string;
  /** Also store the OpenRouter key as a Worker secret so cloud editors can generate images. */
  withOpenRouter?: boolean;
  log?: (msg: string) => void;
}

function wranglerBin(): string {
  const local = path.join(ROOT, 'node_modules', '.bin', 'wrangler');
  return existsSync(local) ? local : 'wrangler';
}

async function wrangler(args: string[], input?: string): Promise<string> {
  const env = { ...process.env, CI: '1', WRANGLER_SEND_METRICS: 'false' };
  if (input === undefined) {
    const { stdout } = await run(wranglerBin(), args, { cwd: ROOT, env, maxBuffer: 50_000_000 });
    return stdout;
  }
  return new Promise((resolve, reject) => {
    const child = spawn(wranglerBin(), args, { cwd: ROOT, env });
    let out = '';
    let err = '';
    child.stdout.on('data', (d) => (out += d));
    child.stderr.on('data', (d) => (err += d));
    child.on('close', (code) => (code === 0 ? resolve(out) : reject(new Error(err || out || `wrangler exited ${code}`))));
    child.stdin.end(input);
  });
}

async function shell(cmd: string, args: string[]) {
  await run(cmd, args, { cwd: ROOT, env: process.env, maxBuffer: 50_000_000 });
}

/** Replace the Worker's workspace key; old keys stop working immediately. */
export async function rotateWorkspaceKey(): Promise<string> {
  const config = loadConfig();
  if (!config) throw new Error('No cloud configured. Run `videdit deploy` first.');
  if (!process.env.CLOUDFLARE_API_TOKEN) throw new Error('Set CLOUDFLARE_API_TOKEN to change the workspace key.');
  const workspaceKey = newId(40);
  await wrangler(['secret', 'put', 'WORKSPACE_KEY'], workspaceKey);
  saveConfig({ serverUrl: config.serverUrl, workspaceKey });
  return workspaceKey;
}

export async function deploy(opts: DeployOptions = {}): Promise<string> {
  const log = opts.log ?? console.log;
  const name = opts.name ?? 'videdit';
  const dbName = name;
  const bucket = `${name}-media`;
  if (!process.env.CLOUDFLARE_API_TOKEN) throw new Error('Set CLOUDFLARE_API_TOKEN first (Workers, D1 and R2 edit permissions).');

  log('Checking Cloudflare account…');
  await wrangler(['whoami']);

  const dbs = JSON.parse(await wrangler(['d1', 'list', '--json'])) as { uuid: string; name: string }[];
  let db = dbs.find((d) => d.name === dbName);
  if (!db) {
    log(`Creating D1 database ${dbName}…`);
    await wrangler(['d1', 'create', dbName]);
    db = (JSON.parse(await wrangler(['d1', 'list', '--json'])) as { uuid: string; name: string }[]).find((d) => d.name === dbName);
    if (!db) throw new Error('D1 database was not created');
  }

  const buckets = await wrangler(['r2', 'bucket', 'list']);
  if (!new RegExp(`name:\\s+${bucket}\\s*$`, 'm').test(buckets)) {
    log(`Creating R2 bucket ${bucket}…`);
    await wrangler(['r2', 'bucket', 'create', bucket]);
  }

  const template = readFileSync(path.join(ROOT, 'wrangler.example.jsonc'), 'utf8');
  const config = template
    .replace(/^\/\/.*\n/, '// Generated by `videdit deploy`. Not committed.\n')
    .replace('"name": "videdit"', `"name": "${name}"`)
    .replace('"database_name": "videdit"', `"database_name": "${dbName}"`)
    .replace('YOUR_D1_DATABASE_ID', db.uuid)
    .replace('"bucket_name": "videdit-media"', `"bucket_name": "${bucket}"`);
  writeFileSync(path.join(ROOT, 'wrangler.jsonc'), config);

  log('Applying database migrations…');
  await wrangler(['d1', 'migrations', 'apply', dbName, '--remote']);

  log('Building the web app…');
  await shell(process.execPath, [path.join(ROOT, 'node_modules', 'vite', 'bin', 'vite.js'), 'build']);

  log('Deploying the Worker…');
  const out = await wrangler(['deploy']);
  const url = out.match(/https:\/\/[\w.-]+\.workers\.dev/)?.[0];
  if (!url) throw new Error(`Deployed, but could not find the workers.dev URL in wrangler output:\n${out}`);

  // Keep the existing workspace key when redeploying the same server.
  const existing = loadConfig();
  const workspaceKey = existing && existing.serverUrl === url ? existing.workspaceKey : newId(40);
  log('Setting the workspace key…');
  await wrangler(['secret', 'put', 'WORKSPACE_KEY'], workspaceKey);
  saveConfig({ serverUrl: url, workspaceKey });
  if (opts.withOpenRouter) {
    const key = process.env.VIDEDIT_OPENROUTER_API_KEY ?? process.env.OPENROUTER_API_KEY ?? readConfigFile().openrouterKey;
    if (!key) throw new Error('--with-openrouter needs OPENROUTER_API_KEY or `videdit config openrouter-key`.');
    log('Enabling AI image generation (OPENROUTER_API_KEY secret)…');
    await wrangler(['secret', 'put', 'OPENROUTER_API_KEY'], key);
  }

  for (let i = 0; i < 20; i++) {
    const res = await fetch(`${url}/api/workspace`, { headers: { 'x-workspace-key': workspaceKey } }).catch(() => null);
    if (res?.ok && ((await res.json()) as { ok: boolean }).ok) return url;
    await new Promise((r) => setTimeout(r, 1500));
  }
  throw new Error(`Deployed to ${url}, but the workspace key check did not pass yet. Try \`videdit doctor\` in a minute.`);
}
